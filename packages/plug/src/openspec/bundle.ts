import { randomBytes } from 'node:crypto';
import { existsSync } from 'node:fs';
import { mkdir, readFile, rename, rm, writeFile } from 'node:fs/promises';
import { join, resolve } from 'node:path';
import { assertContract, validateInput } from '../contracts/index';
import type { DesignInput, DesignRecommendation } from '../contracts/index';
import {
  effectiveArchitectureId,
  explainDesign,
  suggestDesign,
} from '../recommender/index';
import { hash } from '../recommender/policy';
import { importWorkflowSpec, readSpecSource, workflowSpecYaml } from './index';
import {
  recordRevision,
  revisionId,
  validateRevisionSource,
} from './revisions';
import type { RevisionSource } from './revisions';
export const specFiles = {
  workflow: 'workflow.yaml',
  input: 'design-input.json',
  design: 'design.json',
  explanation: 'design.md',
  guide: 'AGENTS.md',
} as const;
export interface SpecSummary {
  directory: '.plug';
  files: string[];
  inputHash: string;
  designHash: string;
  revisionId: string;
  connections: {
    connectionId: string;
    caller: string;
    downstream: string;
    selectedId: string | null;
    selectedArchitectureId: string | null;
    policyDecisionNeeded: boolean;
  }[];
  missingInformation: string[];
}
export interface SpecWrite extends SpecSummary {
  gaps: string[];
  lossless: boolean;
}
export interface SpecState {
  present: boolean;
  /** design.json was computed for design-input.json and workflow.yaml matches it. */
  consistent: boolean;
  /** workflow.yaml differs from design-input.json, e.g. after an agent edited it. */
  workflowEdited: boolean;
  problems: string[];
  summary: SpecSummary | null;
  input: DesignInput | null;
  design: DesignRecommendation | null;
  workflow: string | null;
  currentRevisionId: string | null;
}
const writes = new Map<string, Promise<unknown>>();
export const specDir = (workspaceDir: string) =>
  join(resolve(workspaceDir), '.plug');
export function summarize(
  input: DesignInput,
  design: DesignRecommendation,
  workflow = workflowSpecYaml(input, design),
): SpecSummary {
  const name = (id: string) => input.systems.find((s) => s.id === id)!.name;
  return {
    directory: '.plug',
    files: Object.values(specFiles).map((f) => `.plug/${f}`),
    inputHash: design.inputHash,
    designHash: design.designHash,
    revisionId: revisionId(workflow),
    connections: design.connections.map((r) => {
      const c = input.connections.find((x) => x.id === r.connectionId)!;
      return {
        connectionId: r.connectionId,
        caller: `${name(c.callerSystemId)} ${c.callerOperationId}`,
        downstream: `${name(c.downstreamSystemId)} ${c.downstreamOperationId}`,
        selectedId: r.selectedId,
        selectedArchitectureId: effectiveArchitectureId(r),
        policyDecisionNeeded: r.policyDecisionNeeded,
      };
    }),
    missingInformation: design.missingInformation,
  };
}
function guide(summary: SpecSummary): string {
  const rows = summary.connections
    .map(
      (c) =>
        `| \`${c.connectionId}\` | ${c.caller} → ${c.downstream} | ${c.selectedArchitectureId ?? 'none feasible yet'} |`,
    )
    .join('\n');
  return `# Plug integration spec

Generated by Plug; regenerated on every update. Input \`${summary.inputHash}\`,
design \`${summary.designHash}\`, revision \`${summary.revisionId}\`.

- \`workflow.yaml\`: Open Workflow Specification 1.0 document and the spec of
  record for how this project integrates with other systems. One call task per
  connection carries its priorities and latency target; \`document.metadata.plug\`
  holds the canonical input.
- \`design-input.json\`: the canonical Plug input with systems, connections,
  operational facts and their evidence.
- \`design.json\`: the recommendation with the selected architecture, proofs and
  unknowns per connection.
- \`design.md\`: the explanation and implementation tasks.

| Connection | Caller → downstream | Selected architecture |
|---|---|---|
${rows}

## Keeping the spec current

- Read the latest spec with the Plug MCP tool \`plug_get_spec\` or from these
  files before changing an integration.
- When code changes an integration (operation, endpoint, timeout, retry, cache,
  queue or required experience), update the spec with \`plug_update_spec\`
  (pass the edited \`workflow.yaml\` or a DesignInput) or run
  \`npx plug spec .plug/workflow.yaml\`. Do not hand-edit the JSON files.
- Unknown facts stay unknown: never invent latency, quota, cache permission or
  delivery guarantees. Record them as unknown and list what is needed.
- Adding a host authorizes inspection of its exposed integration points, but
  only explicit Plug probe and verify actions may call them. Never call a
  supplied endpoint during analysis, review or spec generation; never
  automatically execute writes or unknown-effect operations.
- Treat \`.plug/manifest.json\` and \`.plug/verifications.jsonl\` as
  timestamped local-workbench evidence. Preserve vantage, window, sample size,
  source timestamps, cancellation and runtime bounds. They are not production
  measurements, traffic SLOs or permission to cache.
- A design review may recommend an architecture, but only the author may adopt
  or clear it. Re-run deterministic verification after facts or the spec
  revision changes.
- Register the MCP server for this project with
  \`npx plug mcp install --ide cursor\` (or \`vscode\`, \`claude\`).
`;
}
async function atomic(path: string, text: string) {
  const temp = `${path}.${process.pid}.${randomBytes(4).toString('hex')}.tmp`;
  try {
    await writeFile(temp, text);
    await rename(temp, path);
  } catch (e) {
    await rm(temp, { force: true });
    throw e;
  }
}
/** Validates, analyzes and writes `<workspace>/.plug/`; writes are serialized per directory. */
export async function writeSpecBundle(
  workspaceDir: string,
  specSource: unknown,
  source: RevisionSource = 'cli',
): Promise<SpecWrite> {
  const dir = specDir(workspaceDir);
  const revisionSource = validateRevisionSource(source);
  const { input, gaps, lossless } = readSpecSource(specSource);
  const design = suggestDesign(input);
  const workflow = workflowSpecYaml(input, design);
  const summary = summarize(input, design, workflow);
  const files: [string, string][] = [
    [specFiles.workflow, workflow],
    [specFiles.input, JSON.stringify(input, null, 2) + '\n'],
    [specFiles.design, JSON.stringify(design, null, 2) + '\n'],
    [specFiles.explanation, explainDesign(design)],
    [specFiles.guide, guide(summary)],
  ];
  const run = (writes.get(dir) ?? Promise.resolve())
    .catch(() => undefined)
    .then(async () => {
      const previousInput = await readFile(join(dir, specFiles.input), 'utf8')
        .then((text) => validateInput(JSON.parse(text)))
        .catch(() => null);
      await mkdir(dir, { recursive: true });
      for (const [name, text] of files) await atomic(join(dir, name), text);
      await recordRevision(
        workspaceDir,
        workflow,
        previousInput,
        input,
        design,
        revisionSource,
      );
      return { ...summary, gaps, lossless };
    });
  writes.set(dir, run);
  return run;
}
export async function readSpecBundle(workspaceDir: string): Promise<SpecState> {
  const dir = specDir(workspaceDir);
  const empty: SpecState = {
    present: false,
    consistent: false,
    workflowEdited: false,
    problems: [],
    summary: null,
    input: null,
    design: null,
    workflow: null,
    currentRevisionId: null,
  };
  const path = (f: string) => join(dir, f);
  if (!existsSync(path(specFiles.input))) return empty;
  const state: SpecState = { ...empty, present: true };
  try {
    state.input = validateInput(
      JSON.parse(await readFile(path(specFiles.input), 'utf8')),
    );
  } catch (e) {
    state.problems.push(
      `design-input.json is invalid: ${(e as Error).message}`,
    );
    return state;
  }
  try {
    const design = JSON.parse(await readFile(path(specFiles.design), 'utf8'));
    assertContract<DesignRecommendation>('DesignRecommendation', design);
    if (design.inputHash === hash(state.input)) state.design = design;
    else
      state.problems.push(
        'design.json was computed for a different input; regenerate the spec.',
      );
  } catch (e) {
    state.problems.push(
      `design.json is missing or invalid: ${(e as Error).message}`,
    );
  }
  state.workflow = await readFile(path(specFiles.workflow), 'utf8').catch(
    () => null,
  );
  if (state.workflow !== null)
    state.currentRevisionId = revisionId(state.workflow);
  if (state.workflow === null)
    state.problems.push('workflow.yaml is missing; regenerate the spec.');
  else
    try {
      const imported = importWorkflowSpec(state.workflow);
      state.workflowEdited =
        !imported.lossless || hash(imported.input) !== hash(state.input);
    } catch (e) {
      state.workflowEdited = true;
      state.problems.push(`workflow.yaml is invalid: ${(e as Error).message}`);
    }
  if (state.workflowEdited)
    state.problems.push(
      'workflow.yaml was edited after generation; apply it with plug_update_spec or plug spec .plug/workflow.yaml.',
    );
  if (state.design && state.workflow)
    state.summary = summarize(state.input, state.design, state.workflow);
  state.consistent = state.problems.length === 0;
  return state;
}
